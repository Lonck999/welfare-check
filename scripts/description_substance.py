"""判斷一筆補助的 description 是不是「空殼」。

🔴 2026-10-01 建立。起因：前一版用**白名單**（「未查得／查無／待補／尚未」
   四個詞）分類，實測漏掉兩種真空殼：

   · id 209「🔴 金額未在官方頁面列出，詳見來源網址。」
     ⇒ **它自己宣告沒抓到，但沒用白名單裡的任何一個詞**
   · id 510「臺南市生活救助。其他條件：急難事由生活陷困者」
     ⇒ 22 字，只是把補助名稱重寫一次 ＋ 一句資格，**零實質資訊**

🔴 白名單型判準永遠會漏下一種寫法（`~/.hermes/AGENTS.md` §7）——
   補白名單只是修掉今天這兩筆，並替下一種寫法重新安裝同一個 bug。

✅ 改成偵測**後果**：這段文字有沒有讓使用者「知道能領什麼、怎麼領」。
   三個獨立訊號：
     ① 有金額（數字＋元／%／成）
     ② 有可操作的細節（應備文件、受理期間、申請方式、計算方式…）
     ③ 扣掉補助名稱與來源註記後還剩多少字

⚠️ 為什麼不只用長度：有些描述字數不少但全是罰則與備註，
   沒有金額也沒有申請方式 —— 長度單獨用會把它放行。
⚠️ 為什麼不只用金額：有些補助本來就是實物或服務（職業訓練、手語翻譯），
   沒有金額是正常的 —— 只看金額會誤殺它們。
"""
from __future__ import annotations

import re

# ① 金額訊號 —— 數字 ＋ 單位。🔴 前面不可是條號／年月日（那是假金額）
AMOUNT_RE = re.compile(
    r"(?<![第條項款編號年月日])"
    r"(?:[1-9]\d{0,2}(?:,\d{3})+|[1-9]\d{2,}|[一二三四五六七八九十百千萬]{2,})"
    r"\s*(?:元|萬元|元整|％|%|成)"
)

# ② 可操作細節 —— 看了之後知道「怎麼領」或「誰能領」
#
# 🔴 2026-10-01 補第二批（實測 id 716 被誤判成 thin 才發現）：
#    「申辦／登記／報名／抽籤／錄取」是**最直接的「怎麼領」**，第一版全漏。
#    id 716「公立幼兒園優先入園」有完整的申辦資格六款、線上與現場登記方式、
#    抽籤錄取流程 —— 它**沒有金額是因為這個補助本來就不發錢**（給的是入園機會）。
#    ⚠️ 補這批實測：14 筆 thin → ok，**0 筆 empty 被誤救**（有量過才改）。
ACTIONABLE = (
    "應備", "檢附", "備齊", "文件", "證明", "申請書", "表格",
    "受理", "期間", "自即日", "每年", "每月", "逾期", "截止",
    "申請方式", "受理單位", "洽詢", "承辦", "窗口", "線上申請",
    "計算方式", "核算", "按月", "按次", "最高", "上限", "補助標準",
    "須年滿", "設籍", "實際居住",
    # 第二批：申辦流程
    "申辦", "登記", "報名", "抽籤", "錄取", "逕至",
    "專線", "分機", "聯絡電話",
)

# 🔴 這些詞代表「資料不在這裡，去別處問」—— 它們**看起來像**可操作細節
#    （「請洽 XXX 委員會」確實告訴你去哪），但那正是空殼的標準寫法。
#    ⚠️ id 731 實測：「🔴 本筆為官方資料集索引 —— 來源僅提供項目名稱，
#       未含補助金額與資格門檻。實際補助項目、金額與申請條件**請洽**…」
#       —— 補上「請洽」會把它從 empty 救成 ok，那是錯的。
#    ⇒ 「請洽」不列入 ACTIONABLE，只有「洽詢／承辦／窗口」那類
#       **搭配實質內容出現**的才算。
REFER_ELSEWHERE = ("請洽", "請向", "請至各", "自行查證", "另行查證")

# 🔴 這些詞是「我沒抓到」的自我宣告 —— 但**它宣告的範圍只有它自己那一句**。
#
# ⚠️ 2026-10-01 踩雷：第一版寫成「只要出現就判 empty」，結果把
#    id 219（647 字）判成空殼 —— 它前 299 字是完整的法規原文
#    （補助對象、設籍滿一年、非自願離職認定、勞基法條號），
#    第 299 字才出現「🔴 金額未在官方頁面列出」，
#    後面還誠實列出看到的三個金額並說明無法判定哪個屬於本補助。
#    **那是一筆品質很好的資料，不是空殼。**
#
# 🔴 「金額未在官方頁面列出」的意思是「**金額**沒抓到」，
#    不是「**整筆**沒抓到」。判準必須是：
#      把這些自我宣告的句子**整句剝掉**之後，還剩不剩實質內容？
#
# 🔴 **但列舉詞永遠會漏下一種寫法（今天第三次）** ——
#    id 731 寫「未**含**補助金額」，而清單有「未列出」「未在官方頁面列出」
#    卻沒有「未含」⇒ 一個都沒剝到 ⇒ 判成 thin 而不是 empty。
#    ⇒ 改成 regex **句型**：否定詞 ＋（可選的中間字）＋ 資料類名詞。
SELF_DECLARED_RE = re.compile(
    # ① 否定 ＋ 資料類名詞：「未含補助金額」「未列出資格」「查無資料」
    r"(?:未|無法|沒有|查無|尚未|待)"
    r"[^。！？；\n]{0,12}?"
    r"(?:查得|取得|列出|列載|提供|含|記載|說明|標示|公布|確認|查證)"
    r"|"
    # ② 固定說法
    r"(?:詳見來源網址|請見官方網站|資料不足|待確認|待查|待補)"
)

# 保留舊清單供「理由顯示」與 negative control 用（判定一律走 regex）
SELF_DECLARED_EMPTY = (
    "未查得", "查無", "待補", "尚未",
    "未在官方頁面列出", "未列出", "未含", "詳見來源網址",
    "請見官方網站", "無法取得", "資料不足", "待確認", "待查",
)

# 🔴 剝掉自我宣告時要連同它所在的**整句**一起剝（到下一個句末標點為止），
#    否則殘句會被算進長度。
_SENT_END = "。！？；\n"

MIN_CORE = 20          # 扣掉名稱後低於這個字數 ⇒ empty
MIN_SUBSTANTIVE = 80   # 無金額無細節時，至少要這麼長才不算 thin


def normalise(text: str) -> str:
    return re.sub(r"\s+", "", text or "")


def strip_boilerplate(desc: str, name: str) -> str:
    """🔴 把「補助名稱」本身與來源註記從描述裡扣掉再量長度。

    id 510 的描述是「臺南市生活救助。其他條件：急難事由生活陷困者」——
    前半就是 name，扣掉只剩 11 字。
    """
    t = normalise(desc)
    n = normalise(name)
    # 🔴 名稱常帶「（地方明細）」「（全國概況）」後綴，先剝掉再比對
    n = re.sub(r"[（(](?:地方明細|全國概況)[）)]", "", n)
    if n and n in t:
        t = t.replace(n, "", 1)
    t = re.sub(r"[（(]來源[：:][^）)]*[）)]", "", t)
    t = re.sub(r"https?://\S+", "", t)
    return t


def _drop_sentences_containing(text: str, needles) -> tuple[str, list[str]]:
    """把「含有指定字串」的整句剝掉。

    🔴 抽成共用函式的理由：`drop_self_declared`（自我宣告）與
       `REFER_ELSEWHERE`（去別處問）用的是同一套「剝整句」邏輯 ——
       各寫一份的話修了一邊另一邊照舊。

    `needles` 可以是字串序列，也可以是 compiled regex。
    """
    t = text or ""
    found: list[str] = []
    # 🔴 上限避免萬一比對與剝除邏輯互相打架時無限迴圈
    for _ in range(40):
        if hasattr(needles, "search"):
            m = needles.search(t)
            if not m:
                break
            i, j, hit = m.start(), m.end(), m.group(0)
        else:
            cands = [(t.find(n), n) for n in needles if n in t]
            if not cands:
                break
            i, hit = min(cands)
            j = i + len(hit)
        start = 0
        for k in range(i - 1, -1, -1):
            if t[k] in _SENT_END:
                start = k + 1
                break
        end = len(t)
        for k in range(j, len(t)):
            if t[k] in _SENT_END:
                end = k + 1
                break
        found.append(hit)
        t = t[:start] + t[end:]
    return t, found


def drop_self_declared(text: str) -> tuple[str, list[str]]:
    """把「自我宣告沒抓到」的句子整句剝掉。

    🔴 用 `SELF_DECLARED_RE`（句型）而非列舉詞 —— 列舉永遠會漏下一種寫法
       （id 731 的「未**含**」就是漏掉的那一種）。
    """
    return _drop_sentences_containing(text, SELF_DECLARED_RE)


def verdict(desc: str, name: str = "") -> tuple[str, str]:
    """回傳 (判定, 理由)。判定 ∈ {'empty', 'thin', 'ok'}。"""
    if not desc or not desc.strip():
        return "empty", "描述為空"

    # 🔴 先把自我宣告的句子剝掉，再看「剩下的」有沒有內容
    #    —— 不可因為出現那些詞就直接判 empty（id 219 的教訓）
    rest, declared = drop_self_declared(desc)
    t = normalise(rest)
    core = strip_boilerplate(rest, name)

    # 🔴 金額檢查必須在長度檢查**之前**（2026-10-01 雙向驗證抓到）：
    #    「發給一萬八千元。」扣掉名稱只剩 8 字，但它**有金額**
    #    —— 金額是最強的訊號，不該被長度否決。
    m = AMOUNT_RE.search(t)
    if m:
        return "ok", f"有金額（{m.group(0)}）"
    hits = [k for k in ACTIONABLE if k in t]
    if hits:
        suffix = f"；另有自我宣告「{declared[0]}」" if declared else ""
        return "ok", f"有可操作細節（{'、'.join(hits[:3])}）{suffix}"

    # 🔴 「請洽 XXX」這類「去別處問」**不算**內容 —— 它也要整句剝掉。
    #    ⚠️ id 731 實測：剝掉「未含補助金額」那句後還剩
    #       「實際補助項目、金額與申請條件請洽臺中市政府原住民族事務委員會。」
    #       —— 那 35 字看起來像內容，實際上只是把人推去別的地方。
    #    🔴 第一版只把它用在「理由顯示」而沒進判定 ⇒ 判成 thin 而非 empty。
    #       **宣告一個概念不等於它生效。**
    refer = [k for k in REFER_ELSEWHERE if k in t]
    if refer:
        rest2, _ = _drop_sentences_containing(rest, REFER_ELSEWHERE)
        core = strip_boilerplate(rest2, name)

    if len(core) < MIN_CORE:
        why = (f"自我宣告沒抓到（「{declared[0]}」），"
               f"剝掉後只剩 {len(core)} 字") if declared else \
              f"扣掉名稱與來源註記後只剩 {len(core)} 字"
        if refer:
            why += f"；只叫人去別處問（「{refer[0]}」）"
        return "empty", why
    if len(core) >= MIN_SUBSTANTIVE:
        why = f"{len(core)} 字但無金額、無可操作細節"
        if refer:
            why += f"；只叫人去別處問（「{refer[0]}」）"
        return "thin", why
    return "thin", f"只有 {len(core)} 字且無金額、無可操作細節"


