#!/usr/bin/env python3
"""「福利／補助／權益」的判定關鍵字 —— 🔴 唯一來源。

所有腳本一律 `from benefit_keywords import BENEFIT_KW`，
**不可各自維護一份**。

🔴 為什麼需要這個檔：
   2026-09-24 發現兩支腳本的關鍵字不一致
   （`agency_verify_run` 少了「優惠」、`agency_benefit_evidence` 少了「獎助學金」）
   ⇒ 同一個機關，兩支腳本會給出不同答案，而且沒有任何訊號。

收錄判準（Lonck 2026-09-24 定案）：**錢的流向**
   · 給你錢 → 收
   · 少收你錢 → 收
   · 還你錢 → 收
   · 晚付（分期、緩繳）→ 收（急難時真的救命，且極度時效敏感）

完整說明見 `福利範圍定義.md`。
"""
from __future__ import annotations

BENEFIT_KW: tuple[str, ...] = (
    # ── 給你錢 ──
    "補助", "津貼", "給付", "獎助", "獎助學金", "獎勵金", "補貼",
    "救助", "救助金", "慰問金", "扶助", "年金", "紓困",
    # ── 少收你錢 ──
    "減免", "優惠", "免徵",
    # ── 還你錢 ──
    "退稅", "退費",
    # ── 晚付 ──
    "分期", "緩繳",
)

# 🔴 **刻意排除**，每一個都有實測理由（不可憑直覺加回來）：
EXCLUDED = {
    "展延": ("84 筆全是保稅倉庫／自由港區／園區事業的報關作業。"
             "這個字聽起來像『延期繳費』，實際跟個人福利無關。"),
    "抵減": ("7 筆全是『公司投資抵減』『中小企業研發支出』等企業稅務。"
             "個人綜所稅雖也有抵減，但 e 政府資料裡沒有 —— "
             "沒證據就先不收，日後找到個人適用的再單獨加。"),
}

# 🔴 只採信官方網域 —— 資料庫現有 61% 來源是商周／今周刊，
#    而實測死掉的連結**全是非官方站，官方一個都沒死**。
OFFICIAL_DOMAIN_RE = r"https?://[^/]*\.(gov\.tw|edu\.tw)(/|$)"


def is_benefit_title(title: str) -> bool:
    """標題像不像補助類服務。

    ⚠️ 這**只是篩候選**，不是結論 —— 關鍵字兩個方向都會錯：
       偽陽性：「財政部印刷廠」（搜到經濟部的頁面而誤判）
       偽陰性：「經濟部能源署」（名稱裡沒有任何福利字樣）
    """
    return any(k in (title or "") for k in BENEFIT_KW)


if __name__ == "__main__":
    print(f"收錄關鍵字 {len(BENEFIT_KW)} 個：")
    print("  " + "、".join(BENEFIT_KW))
    print(f"\n🔴 刻意排除 {len(EXCLUDED)} 個：")
    for k, why in EXCLUDED.items():
        print(f"  {k}：{why}")
