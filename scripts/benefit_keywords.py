#!/usr/bin/env python3
"""「福利／補助／權益」的判定關鍵字 —— 🔴 唯一來源。

所有腳本一律 `from benefit_keywords import BENEFIT_KW`，
**不可各自維護一份**。

🔴 為什麼需要這個檔：
   2026-09-24 發現兩支腳本的關鍵字不一致
   （`agency_verify_run` 少了「優惠」、`agency_benefit_evidence` 少了「獎助學金」）
   ⇒ 同一個機關，兩支腳本會給出不同答案，而且沒有任何訊號。

收錄判準（Lonck 2026-09-24 定案）：**錢的流向**
   · 給你錢 → 收
   · 少收你錢 → 收
   · 還你錢 → 收
   · 晚付（分期、緩繳）→ 收（急難時真的救命，且極度時效敏感）

完整說明見 `福利範圍定義.md`。
"""
from __future__ import annotations

BENEFIT_KW: tuple[str, ...] = (
    # ── 給你錢 ──
    "補助", "津貼", "給付", "獎助", "獎助學金", "獎勵金", "補貼",
    "救助", "救助金", "慰問金", "扶助", "年金", "紓困",
    # ── 少收你錢 ──
    "減免", "優惠", "免徵",
    # ── 還你錢 ──
    "退稅", "退費",
    # ── 晚付 ──
    "分期", "緩繳",
)

# 🔴 **刻意排除**，每一個都有實測理由（不可憑直覺加回來）：
EXCLUDED = {
    "展延": ("84 筆全是保稅倉庫／自由港區／園區事業的報關作業。"
             "這個字聽起來像『延期繳費』，實際跟個人福利無關。"),
    "抵減": ("7 筆全是『公司投資抵減』『中小企業研發支出』等企業稅務。"
             "個人綜所稅雖也有抵減，但 e 政府資料裡沒有 —— "
             "沒證據就先不收，日後找到個人適用的再單獨加。"),
}

# 🔴 只採信官方網域 —— 資料庫現有 61% 來源是商周／今周刊，
#    而實測死掉的連結**全是非官方站，官方一個都沒死**。
#
# ⚠️ **`.gov.taipei` 也是官方**（2026-09-24 踩到）：
#    臺北市是台灣唯一有城市頂級域名的縣市，
#    依《臺北市政府所屬機關網域命名要點》第四點，
#    **一級機關網域以 `gov.taipei` 為二階網域**
#    （`police.gov.taipei`、`land.gov.taipei`、`udd.gov.taipei`…）。
#    第一版只認 `.gov.tw`，導致**臺北市所有局處都被判成「查無官方頁面」**。
#    ⚠️ 其他 21 縣市實測都是 `.gov.tw`，只有臺北市特殊。
#    🔴 `edu.taipei`（學校）與 `org.taipei`（行政法人）不收。
OFFICIAL_DOMAIN_RE = (r"https?://[^/]*("
                      r"\.(gov|edu)\.tw"
                      r"|(^|\.)gov\.taipei"
                      r")(/|$|:)")


# 🔴 **命中關鍵字 ≠ 這個機關在發補助**（2026-09-24 實測，26 筆有 18 筆誤判）。
#    「補助」二字在政府網站無所不在。以下上下文一律**先剔除再比對**：
NOT_BENEFIT_CTX = (
    r"\[?是否受機關補助\]?\s*[否是]?",        # 表單欄位
    r"補助計畫項下財產[^\n]{0,20}",            # 財產申報表說明
    r"利益衝突迴避[^\n]{0,30}補助交易[^\n]{0,20}",  # 系統名稱
    r"中央各部會補助款[^\n]{0,30}",            # 中央撥給地方，非民眾可申請
    r"拆遷補償[^\n]{0,10}人口搬遷補助費[^\n]{0,20}",  # 工程拆遷補償
    r"出差旅費報支[^\n]{0,40}補助要點[^\n]{0,20}",   # 公務員報帳
    r"講習費用補助要點[^\n]{0,20}",
    r"議員建議補助[^\n]{0,20}",                # 議員配合款
)


def is_benefit_title(title: str) -> bool:
    """標題像不像補助類服務。

    ⚠️ 這**只是篩候選**，不是結論 —— 關鍵字兩個方向都會錯：
       偽陽性：「財政部印刷廠」（搜到經濟部的頁面而誤判）
       偽陰性：「經濟部能源署」（名稱裡沒有任何福利字樣）
    """
    return any(k in (title or "") for k in BENEFIT_KW)


if __name__ == "__main__":
    print(f"收錄關鍵字 {len(BENEFIT_KW)} 個：")
    print("  " + "、".join(BENEFIT_KW))
    print(f"\n🔴 刻意排除 {len(EXCLUDED)} 個：")
    for k, why in EXCLUDED.items():
        print(f"  {k}：{why}")
