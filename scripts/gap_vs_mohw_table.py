def main() -> int:
    conn = psycopg2.connect(dbname="welfare_check")
    cur = conn.cursor()

    # 🔴 **手抄表必須先自我校驗**（官方表最後一行「項目數」就是校驗碼）。
    #    我第一次抄就漏了「老人普查」——基隆 13≠14、屏東 16≠17 才抓到。
    #    ⚠️ 沒有這個檢查的話，缺口報告會少算，而且看起來完全正常。
    OFFICIAL_COUNT = [18, 14, 12, 16, 19, 5, 14, 20, 14, 17]
    bad = []
    for i, cty in enumerate(COUNTIES):
        mine = sum(1 for _, f in TABLE if i < len(f) and f[i] == "V")
        if mine != OFFICIAL_COUNT[i]:
            bad.append(f"{cty} 抄了 {mine} 官方 {OFFICIAL_COUNT[i]}")
    if bad:
        print("🔴 手抄的對照表與官方「項目數」不符，先修表再跑：")
        for b in bad:
            print(f"   · {b}")
        return 1
    print(f"✅ 對照表校驗通過（{len(TABLE)} 項 × {len(COUNTIES)} 縣市）\n")

    print("=== 衛福部官方對照表 vs 我們的資料庫 ===\n")
    gaps: dict[str, list[str]] = {}
    total_should = total_have = 0

    for item, flags in TABLE:
        pats = SYNONYM.get(item, (item,))
        for i, cty in enumerate(COUNTIES):
            if i >= len(flags) or flags[i] != "V":
                continue
            total_should += 1
            # 🔴 比對要含「全國層級」的筆（2026-09-25 修）：
            #    這 6 項是中央訂辦法、地方執行的**全國統一制度**
            #    （育兒津貼、弱勢兒少生活扶助、國民年金保費減免…），
            #    主條目存成 county='全國' —— 任何縣市居民都適用。
            #    ⚠️ 只比對 county=該縣市的話，會把「已經有的」報成缺口，
            #    然後我就會去抓 10 份一模一樣的中央規定。
            like = " OR ".join(
                ["name ~ %s"] * len(pats) + ["description ~ %s"] * len(pats))
            cur.execute(f"""SELECT count(*) FROM benefits
                             WHERE county IN (%s, '全國') AND ({like})""",
                        (cty, *pats, *pats))
            if cur.fetchone()[0]:
                total_have += 1
            else:
                gaps.setdefault(cty, []).append(item)

    print(f"官方標示「有提供」的組合：{total_should} 個")
    print(f"  ✅ 我們已有：{total_have}（{total_have / total_should:.0%}）")
    print(f"  🔴 缺口：{total_should - total_have}\n")

    for cty in COUNTIES:
        miss = gaps.get(cty, [])
        have = sum(1 for it, f in TABLE
                   if COUNTIES.index(cty) < len(f)
                   and f[COUNTIES.index(cty)] == "V") - len(miss)
        mark = "✅" if not miss else "🔴"
        print(f"  {mark} {cty}　已有 {have}　缺 {len(miss)}")
        for m in miss[:6]:
            print(f"       · {m}")
        if len(miss) > 6:
            print(f"       …還有 {len(miss) - 6} 項")
    return 0


if __name__ == "__main__":
    sys.exit(main())
